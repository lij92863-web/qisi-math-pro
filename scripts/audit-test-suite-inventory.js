// Test-suite inventory: how many tests each file holds, what kind of evidence it produces, and
// which files only check that something exists. Read-only; it never edits or deletes tests.
//
// Usage: node scripts/audit-test-suite-inventory.js [--json <path>] [--markdown <path>]
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const readArg = (name, fallback) => {
    const index = process.argv.indexOf(name);
    return index >= 0 && process.argv[index + 1] ? process.argv[index + 1] : fallback;
};
const jsonPath = readArg('--json', path.join(ROOT, 'artifacts', 'audit-baseline', 'test-inventory.json'));
const markdownPath = readArg('--markdown', path.join(ROOT, 'docs', 'audit', 'TEST_SUITE_INVENTORY.md'));

const testsDir = path.join(ROOT, 'tests');
const files = fs.readdirSync(testsDir)
    .filter(name => name.endsWith('.test.js'))
    .sort();

const rows = files.map(name => {
    const source = fs.readFileSync(path.join(testsDir, name), 'utf8');
    // Files in this suite use both `test(...)` and `describe(...)/it(...)`.
    const testCount = (source.match(/^\s*(?:test|it)\(/gm) || []).length;
    const assertionCount = (source.match(/assert\.\w+\(/g) || []).length;
    const existenceOnly = assertionCount > 0
        && assertionCount === (source.match(/assert\.(?:equal|strictEqual)\(typeof /g) || []).length
        + (source.match(/typeof\s+\w+\s*===?\s*['"]function['"]/g) || []).length;
    const usesBrowser = /require\(['"]playwright['"]\)/.test(source);
    const usesServer = /qisi-local-server\.js/.test(source);
    const hasFixtures = /fixtures\//.test(source);
    const isStaticGrep = /readFileSync\([^)]*main\.html/.test(source)
        || /readFileSync\([^)]*app\.js/.test(source);

    return {
        file: name,
        tests: testCount,
        assertions: assertionCount,
        kind: usesBrowser ? 'product/browser' : (usesServer ? 'integration/server' : 'unit'),
        fixtures: hasFixtures,
        staticSourceScan: isStaticGrep,
        existenceOnly,
        bytes: Buffer.byteLength(source)
    };
});

const totals = rows.reduce((sum, row) => ({
    files: sum.files + 1,
    tests: sum.tests + row.tests,
    browser: sum.browser + (row.kind === 'product/browser' ? 1 : 0),
    server: sum.server + (row.kind === 'integration/server' ? 1 : 0),
    existenceOnly: sum.existenceOnly + (row.existenceOnly ? 1 : 0),
    staticSourceScan: sum.staticSourceScan + (row.staticSourceScan ? 1 : 0)
}), { files: 0, tests: 0, browser: 0, server: 0, existenceOnly: 0, staticSourceScan: 0 });

const report = { generatedAt: new Date().toISOString(), totals, files: rows };
fs.mkdirSync(path.dirname(jsonPath), { recursive: true });
fs.writeFileSync(jsonPath, JSON.stringify(report, null, 2), 'utf8');

const lines = [
    '# Test suite inventory',
    '',
    'Generated by `node scripts/audit-test-suite-inventory.js`. Read-only: it classifies the',
    'existing suite so consolidation can be argued from evidence instead of taste.',
    '',
    '```text',
    `files            ${totals.files}`,
    `tests            ${totals.tests}`,
    `browser-based    ${totals.browser}`,
    `server-based     ${totals.server}`,
    `existence-only   ${totals.existenceOnly}`,
    `static source scans ${totals.staticSourceScan}`,
    '```',
    '',
    '## Files with the most tests',
    '',
    '| file | tests | assertions | kind |',
    '| --- | --- | --- | --- |'
];

for (const row of [...rows].sort((a, b) => b.tests - a.tests).slice(0, 25)) {
    lines.push(`| ${row.file} | ${row.tests} | ${row.assertions} | ${row.kind} |`);
}

lines.push('', '## Files that only check that something exists', '');
for (const row of rows.filter(row => row.existenceOnly)) {
    lines.push(`- ${row.file}`);
}
if (!rows.some(row => row.existenceOnly)) lines.push('- none');

lines.push('', '## Static source scans (grep-style checks on main.html or app.js)', '');
for (const row of rows.filter(row => row.staticSourceScan)) {
    lines.push(`- ${row.file}`);
}
if (!rows.some(row => row.staticSourceScan)) lines.push('- none');

lines.push('');
fs.mkdirSync(path.dirname(markdownPath), { recursive: true });
fs.writeFileSync(markdownPath, lines.join('\n'), 'utf8');

console.log('[test-inventory] files: ' + totals.files + ' tests: ' + totals.tests
    + ' browser: ' + totals.browser + ' server: ' + totals.server);
console.log('[test-inventory] existence-only files: ' + totals.existenceOnly
    + ' | static source scans: ' + totals.staticSourceScan);
console.log('[test-inventory] wrote ' + jsonPath + ' and ' + markdownPath);
